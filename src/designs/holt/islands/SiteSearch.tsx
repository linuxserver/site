import * as React from 'react';
import { Search } from 'lucide-react';
import { Input } from '@/components/ui/input';
import { search, type SearchHit } from '@/lib/pagefind-client';
import type { SearchIndex } from '@/components/islands/CommandSearch';

interface Props {
  indexUrl: string;
  /** Form action, so search works as a plain GET before hydration. */
  action: string;
}

/** Full-text search: image matches from the small index, post matches from Pagefind. Query lives in ?q=. */
export default function SiteSearch({ indexUrl, action }: Props) {
  const [q, setQ] = React.useState('');
  const [index, setIndex] = React.useState<SearchIndex | null>(null);
  const [hits, setHits] = React.useState<SearchHit[] | null | undefined>(undefined);
  const [busy, setBusy] = React.useState(false);

  React.useEffect(() => {
    setQ(new URLSearchParams(location.search).get('q') ?? '');
    fetch(indexUrl).then((r) => r.json()).then(setIndex).catch(() => {});
  }, [indexUrl]);

  React.useEffect(() => {
    const term = q.trim();
    history.replaceState(null, '', term ? `?q=${encodeURIComponent(term)}` : location.pathname);
    if (!term) return setHits(undefined);
    setBusy(true);
    const t = setTimeout(async () => {
      const res = await search(term, 12);
      setHits(res);
      setBusy(false);
    }, 180);
    return () => clearTimeout(t);
  }, [q]);

  const term = q.trim().toLowerCase();
  const images = term && index ? index.images.filter((i) => i.n.includes(term) || i.s.toLowerCase().includes(term) || i.c.some((c) => c.toLowerCase().includes(term))).slice(0, 6) : [];

  return (
    <div>
      <form action={action} method="get" role="search" onSubmit={(e) => e.preventDefault()} className="relative">
        <Search className="pointer-events-none absolute top-1/2 left-5 size-5 -translate-y-1/2 text-muted-foreground" aria-hidden="true" />
        <Input
          type="search"
          name="q"
          value={q}
          onChange={(e) => setQ(e.target.value)}
          placeholder="Search every post and image…"
          aria-label="Search"
          autoFocus
          className="h-14 rounded-full bg-card pr-5 pl-14 text-lg shadow-[var(--holt-shadow)] md:text-lg"
        />
      </form>

      <div className="mt-8" aria-live="polite" aria-busy={busy}>
        {term && images.length > 0 && (
          <section aria-labelledby="sr-images" className="mb-10">
            <h2 id="sr-images" className="font-heading text-xl font-bold text-foreground">Images</h2>
            <ul className="mt-4 grid gap-3 sm:grid-cols-2 lg:grid-cols-3">
              {images.map((i) => (
                <li key={i.u}>
                  <a href={i.u} className="holt-card holt-lift flex items-center gap-3 p-3.5">
                    <span className="grid size-11 shrink-0 place-items-center rounded-xl bg-muted holt-tile p-2">
                      {i.l ? <img src={i.l} alt="" width={28} height={28} className="size-7 object-contain" /> : null}
                    </span>
                    <span className="min-w-0">
                      <span className="block font-semibold text-foreground">{i.n}</span>
                      <span className="block truncate text-sm text-muted-foreground">{i.s}</span>
                    </span>
                  </a>
                </li>
              ))}
            </ul>
          </section>
        )}

        {term && (
          <section aria-labelledby="sr-posts">
            <h2 id="sr-posts" className="font-heading text-xl font-bold text-foreground">Posts</h2>
            {hits === null ? (
              <p className="mt-4 rounded-2xl bg-muted p-4 text-muted-foreground">
                Full-text search is available on the built site (it is generated by <code>npm run build</code>), not in the dev server.
              </p>
            ) : hits && hits.length === 0 ? (
              <p className="mt-4 text-muted-foreground">No posts mention “{q.trim()}”.</p>
            ) : (
              <ol className="mt-4 space-y-3" data-search-results>
                {(hits ?? []).map((h) => (
                  <li key={h.url}>
                    <a href={h.url} className="holt-card holt-lift block p-5">
                      <span className="block font-heading text-lg font-bold text-foreground">{h.title}</span>
                      <span className="mt-1 block text-muted-foreground" dangerouslySetInnerHTML={{ __html: h.excerpt }} />
                    </a>
                  </li>
                ))}
              </ol>
            )}
          </section>
        )}
      </div>
    </div>
  );
}
